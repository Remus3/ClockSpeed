def _bound_port(server: object) -> int:
    """The ephemeral port the running server actually bound.

    Args:
        server: Whatever ``serve`` yielded.

    Returns:
        The port.

    Raises:
        AssertionError: Neither accepted spelling is present, which is a finding
            about the seam rather than about the server.
    """
    port = getattr(server, "port", None)
    if isinstance(port, int) and port > 0:
        return port
    address = getattr(server, "server_address", None)
    if isinstance(address, tuple) and len(address) > 1 and isinstance(address[1], int):
        return int(address[1])
    raise AssertionError(SEAM_NO_PORT)


def _request_path(template: str) -> str:
    """The concrete path to ask for, for a route template.

    Args:
        template: The template, possibly holding ``<id>``.

    Returns:
        The path, with the parameter filled and the documented query attached.
    """
    path = template.replace("<id>", PROBE_ID)
    if template == PLAN_TEMPLATE:
        return f"{path}?target={PROBE_TARGET}"
    return path


def _speak_https(port: int, context: ssl.SSLContext, method: str, path: str) -> tuple[int, bytes]:
    """One verified HTTPS request against the running server.

    Args:
        port: The bound port.
        context: The client's TLS context. ``check_hostname`` is never lowered.
        method: The HTTP method.
        path: The request path.

    Returns:
        The transport code and the raw body.
    """
    connection = http.client.HTTPSConnection(
        LOOPBACK, port, timeout=REQUEST_TIMEOUT_SECONDS, context=context
    )
    try:
        connection.request(method, path)
        answer = connection.getresponse()
        return int(answer.status), answer.read()
    finally:
        connection.close()


def _observe(port: int, context: ssl.SSLContext, template: str, method: str) -> Observed:
    """Drive one endpoint and reduce what came back.

    Args:
        port: The bound port.
        context: The verifying client context.
        template: The route template.
        method: The method to use.

    Returns:
        The reduced observation.
    """
    http_status, raw = _speak_https(port, context, method, _request_path(template))
    body_text = raw.decode("utf-8", errors="replace")
    try:
        payload = json.loads(body_text)
    except ValueError:
        return _reduce(template, method, http_status, {}, body_text, parsed=False)
    if not isinstance(payload, dict):
        return _reduce(template, method, http_status, {}, body_text, parsed=False)
    return _reduce(template, method, http_status, payload, body_text, parsed=True)


def _config(cert_path: Path, key_path: Path, web_dir: Path) -> ServerConfig:
    """The listener configuration these arms run against.

    THE ONE PLACE THIS MODULE NAMES A FIELD IT DID NOT DERIVE. The slice brief
    contracted four public names - ``ServerConfig``, ``serve``, ``ROUTES`` and
    ``contract`` - and did not contract this constructor's fields or ``serve``'s
    arity, so the spelling here is a SEAM ASSUMPTION and is reported as one. It
    is deliberately confined to this function: nothing about the route set, the
    transport codes or the payload shape - the things actually being graded -
    depends on it, so a change here cannot quietly soften an arm.

    ``web_dir`` is an EMPTY directory on purpose. These are the arms for the JSON
    API, and an API that cannot start without dashboard assets present is a
    coupling worth finding rather than worth papering over.

    Args:
        cert_path: The server certificate.
        key_path: Its private key.
        web_dir: Where the dashboard assets would live.

    Returns:
        The configuration.
    """
    return ServerConfig(
        host=LOOPBACK,
        port=EPHEMERAL_PORT,
        cert_path=cert_path,
        key_path=key_path,
        web_dir=web_dir,
    )


