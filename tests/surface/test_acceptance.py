def test_a_planted_answer_on_an_unbuilt_route_is_rejected_over_the_real_wire(
    tls_material: tuple[Path, Path, Path],
) -> None:
    """The fullest form of the vacuity control: a real listener, really lying.

    A second server is stood up on its own ephemeral port with ONE route
    replaced by a handler that returns a perfectly formed 200 on a route the
    partition says is unbuilt. Everything else - the transport, the encoder, the
    client, the reduction - is the same code the honest arms run through, so
    what this grades is the CHECK and nothing else.

    Args:
        tls_material: The certificate pair and the asset directory.
    """
    cert_path, key_path, web_dir = tls_material
    template = UNBUILT[0]
    planted = tuple(
        contract.Route(
            method=route.method,
            template=route.template,
            handler=lambda _params: contract.ok(template, {"cards": []}),
        )
        if route.template == template
        else route
        for route in ROUTES
    )
    swapped = len(planted) - sum(1 for route in planted if route in ROUTES)
    assert swapped == 1, "the plant did not replace exactly one route"

    client = ssl.create_default_context(cafile=str(cert_path))
    with serve(_config(cert_path, key_path, web_dir), planted) as server:
        observed = _observe(_bound_port(server), client, template, "GET")

    served_200 = observed.http_status == contract.HTTP_OK
    assert served_200, "the plant did not reach the wire, so this proves nothing"
    rejected = FAULT_UNBUILT_ROUTE_DID_NOT_REFUSE in honesty_faults(observed)
    assert rejected, "a real server really lying was accepted by the honesty check"


