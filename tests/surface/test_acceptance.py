#: The suite's own redactor rewrote the body, so it held a home path or an
#: account name. Reported as its own id because the redactor answers "something
#: of mine is in here" without saying which of its two classes it was.
CLASS_REDACTOR_FIRED: Final = "redactor-rewrote-the-body"

#: A world token rendered unmasked. NOT one of the four classes ``tests/
#: conftest.py`` registers - those are about a failure report, and this is about
#: a response body - so it carries its own id rather than borrowing
#: ``CLASS_WORLD_NAME``, which names the operator-authored world name instead.
CLASS_SAVE_IDENTIFIER: Final = "save-identifier"

#: A platform account id as the save directory spells one: a long run of digits.
#: The floor is set well above any count, offset, numerator or denominator this
#: API has a reason to render, because a shape detector that fires on an ordinary
#: integer is a detector that gets deleted.
_MIN_ACCOUNT_ID_DIGITS: Final = 15
_ACCOUNT_ID_DIGITS: Final = re.compile(rf"\d{{{_MIN_ACCOUNT_ID_DIGITS},}}")

#: The other spelling of the same identifier, as a 32 character hexadecimal id.
_ACCOUNT_ID_HEX: Final = re.compile(r"(?<![0-9A-Za-z])[0-9a-fA-F]{32}(?![0-9A-Za-z])")

#: A save identifier at its MEASURED length, imported rather than restated. The
#: character class is the one a base64-spelled identifier uses. ``masked_token``
#: renders a prefix plus a short digest and breaks on the colon, so a masked
#: token cannot match this.
_IDENTIFIER_CHARS: Final = "A-Za-z0-9+/=-"
_IDENTIFIER_RUN: Final = rf"[{_IDENTIFIER_CHARS}]{{{WORLD_TOKEN_LENGTH}}}"
_SAVE_IDENTIFIER = re.compile(
    rf"(?<![{_IDENTIFIER_CHARS}]){_IDENTIFIER_RUN}(?![{_IDENTIFIER_CHARS}])"
)


def _known_safe_runs() -> frozenset[str]:
    """Published vocabulary words that happen to be token-shaped.

    A reason code is authored in this repository and is not personal data, but
    ``search_space_too_large`` is exactly as long as a save identifier. Without
    this subtraction the detector would report a correct refusal as a leak, and
    a detector with a false positive is a detector someone switches off.

    Returns:
        Every closed-vocabulary word this API can put on the wire.
    """
    words: set[str] = set()
    words.update(contract.REASONS)
    words.update(contract.STATUSES)
    words.update(contract.PROBLEM_CODES)
    for template in BOOTSTRAP_NINE:
        words.update(part for part in re.split(r"[^A-Za-z0-9_]+", template) if part)
    return frozenset(words)


KNOWN_SAFE_RUNS: Final = _known_safe_runs()


def _home_spellings() -> tuple[str, ...]:
    """Every way this machine's home directory can appear in a JSON body.

    MEASURED, NOT REASONED. The plain string was the whole of this check until a
    throwaway server was made to leak ``str(Path.home())`` through a real
    response. The JSON encoder DOUBLES every separator on this platform, so the
    path reaches the wire in a spelling the plain substring test does not match,
    and that test missed it entirely. The suite redactor happened to catch the
    same body by a different rule, and a check that only works when another
    check works is not a check. The URL-quoted spelling is here for the same
    reason and has not been observed, only anticipated.

    Returns:
        The spellings, longest first.
    """
    plain = str(Path.home())
    if not plain:
        return ()
    spellings = {
        plain,
        plain.replace("\\", "\\\\"),
        plain.replace("\\", "/"),
        plain.replace("\\", "%5C"),
    }
    return tuple(sorted(spellings, key=len, reverse=True))


HOME_SPELLINGS: Final = _home_spellings()


def _personal_data_classes(text: str) -> tuple[str, ...]:
    """Which personal-data classes this text carries, as ids and never as values.

    THE RETURN IS A CLOSED VOCABULARY ON PURPOSE. This result reaches a failure
    message, and a failure message that quotes what it found publishes the very
    thing the arm exists to keep out of a response body.

    Args:
        text: A response body, exactly as it came off the wire.

    Returns:
        The class ids found, in a stable order. Empty when the text is clean.
    """
    found: list[str] = []

    if redact_personal_data(text) != text:
        found.append(CLASS_REDACTOR_FIRED)

    if any(spelling in text for spelling in HOME_SPELLINGS):
        found.append(CLASS_HOME_PATH)

    account = Path.home().name
    if account and re.search(rf"(?<![0-9A-Za-z_]){re.escape(account)}(?![0-9A-Za-z_])", text):
        found.append(CLASS_ACCOUNT_NAME)

    if _ACCOUNT_ID_DIGITS.search(text) or _ACCOUNT_ID_HEX.search(text):
        found.append(CLASS_ACCOUNT_ID)

    if any(run not in KNOWN_SAFE_RUNS for run in _SAVE_IDENTIFIER.findall(text)):
        found.append(CLASS_SAVE_IDENTIFIER)

    return tuple(found)


