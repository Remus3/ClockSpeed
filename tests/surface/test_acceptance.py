_SECTION_71: Final = "### 7.1"
_NEXT_SECTION: Final = "\n### "
_BACKTICKED: Final = re.compile(r"`([^`]+)`")


def bootstrap_endpoints(document: str) -> tuple[str, ...]:
    """The endpoint templates BOOTSTRAP.md section 7.1 names, in document order.

    Args:
        document: The whole of ``BOOTSTRAP.md``.

    Returns:
        Each backticked ``/api`` span in that section, query string removed, with
        duplicates dropped and order preserved.

    Raises:
        ValueError: The section heading or its terminator is absent, which means
            the document moved under this parser rather than that the API is
            wrong.
    """
    head = document.index(_SECTION_71) + len(_SECTION_71)
    body = document[head:]
    body = body[: body.index(_NEXT_SECTION)]

    found: list[str] = []
    for span in _BACKTICKED.findall(body):
        if not span.startswith("/api"):
            continue
        template = span.split("?", 1)[0]
        if template not in found:
            found.append(template)
    return tuple(found)


_OPEN_ITEM: Final = re.compile(r"^(CS-\d{3}) - ", re.MULTILINE)


def open_item_ids(roadmap: str) -> frozenset[str]:
    """Every item id that still has an OPEN line in the roadmap.

    ``ROADMAP.md`` holds OPEN work only - a closed item's line is relocated to
    ``docs/LEDGER.md`` - so presence of the line IS the open state.

    Args:
        roadmap: The whole of ``ROADMAP.md``.

    Returns:
        The ids, with no ordering.
    """
    return frozenset(_OPEN_ITEM.findall(roadmap))


