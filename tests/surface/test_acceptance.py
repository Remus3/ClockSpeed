@dataclass(frozen=True)
class Observed:
    """One endpoint's answer, reduced to closed-vocabulary facts.

    NO BODY TEXT AND NO ``data`` VALUES, WHICH IS A DECISION RATHER THAN AN
    OMISSION. A frozen dataclass gets a generated ``__repr__`` that renders every
    field, and pytest renders the locals of a failing frame under ``-l``. Keeping
    values out of the type means the channel cannot open here at all, which is
    stronger than a hand-written ``__repr__`` a later field can outgrow.

    Attributes:
        template: The route template this answer belongs to.
        method: The HTTP method used.
        http_status: The transport code.
        parsed: Whether the body was JSON at all.
        ascii_only: Whether every byte was 7-bit.
        payload_keys: The body's top-level key NAMES.
        status_word: The body's ``status``, which is a closed vocabulary.
        reason_word: The body's ``reason``, likewise closed.
        blocked_by: The item the body blames, which is a ``CS-nnn`` id.
        personal_data_classes: Class ids from :func:`_personal_data_classes`.
        contract_faults: What ``contract.contract_problems`` said, as a second
            and independent opinion. Agreement between it and
            :func:`honesty_faults` is not evidence, so both are asserted.
    """

    template: str
    method: str
    http_status: int
    parsed: bool
    ascii_only: bool
    payload_keys: frozenset[str]
    status_word: str | None
    reason_word: str | None
    blocked_by: str | None
    personal_data_classes: tuple[str, ...]
    contract_faults: tuple[str, ...]


def _text_of(payload: Mapping[str, object]) -> str:
    """Render a payload the way the wire would, for the personal-data scan.

    Args:
        payload: A response body.

    Returns:
        The encoded bytes as text, or the plain ``repr`` when the payload is one
        the published encoder refuses.
    """
    try:
        return contract.encode(payload).decode("ascii")
    except (ValueError, UnicodeError):
        return repr(payload)


def _reduce(
    template: str,
    method: str,
    http_status: int,
    payload: Mapping[str, object],
    body_text: str,
    parsed: bool,
) -> Observed:
    """Reduce one answer to the facts the arms grade. THE ONLY PLACE A BODY GOES.

    Args:
        template: The route template.
        method: The HTTP method used.
        http_status: The transport code.
        payload: The parsed body, or an empty mapping when it did not parse.
        body_text: The body as text, for the personal-data scan.
        parsed: Whether the body was JSON.

    Returns:
        The reduced observation.
    """
    status_word = payload.get("status")
    reason_word = payload.get("reason")
    blocked_by = payload.get("blocked_by")
    response = contract.Response(http_status=http_status, payload=dict(payload))
    return Observed(
        template=template,
        method=method,
        http_status=http_status,
        parsed=parsed,
        ascii_only=body_text.isascii(),
        payload_keys=frozenset(payload),
        status_word=status_word if isinstance(status_word, str) else None,
        reason_word=reason_word if isinstance(reason_word, str) else None,
        blocked_by=blocked_by if isinstance(blocked_by, str) else None,
        personal_data_classes=_personal_data_classes(body_text),
        contract_faults=contract.contract_problems(response),
    )


def observe_response(template: str, method: str, response: contract.Response) -> Observed:
    """Reduce a Response object that never went over the wire.

    Used by the A4 plants, so a planted answer is graded by exactly the code path
    a real one is.

    Args:
        template: The route template to attribute it to.
        method: The method to attribute it to.
        response: The response to reduce.

    Returns:
        The reduced observation.
    """
    return _reduce(
        template=template,
        method=method,
        http_status=response.http_status,
        payload=response.payload,
        body_text=_text_of(response.payload),
        parsed=True,
    )


def _body_faults(observed: Observed) -> tuple[str, ...]:
    """A1's half: the ways the transport code and the body disagree.

    Args:
        observed: The reduced answer.

    Returns:
        The A1 and wire fault ids this answer earns.
    """
    found: list[str] = []

    if not observed.parsed:
        found.append(FAULT_UNPARSED)
    if not observed.ascii_only:
        found.append(FAULT_NON_ASCII)

    if observed.http_status == contract.HTTP_OK:
        if observed.status_word != contract.STATUS_OK:
            found.append(FAULT_OK_BODY_DENIES_IT)
        if "data" not in observed.payload_keys:
            found.append(FAULT_OK_WITHOUT_DATA)
        if "reason" in observed.payload_keys:
            found.append(FAULT_OK_WITH_REASON)
    elif observed.status_word == contract.STATUS_OK:
        found.append(FAULT_REFUSAL_CLAIMS_OK)

    if observed.http_status == contract.HTTP_NOT_IMPLEMENTED and not observed.blocked_by:
        found.append(FAULT_UNBUILT_WITHOUT_BLOCKER)

    return tuple(found)


def _partition_faults(observed: Observed) -> tuple[str, ...]:
    """A3's half: the ways a route answered out of its declared half.

    Args:
        observed: The reduced answer.

    Returns:
        The A3 fault ids this answer earns.
    """
    if observed.template in BACKED:
        if observed.http_status == contract.HTTP_NOT_IMPLEMENTED:
            return (FAULT_BACKED_ROUTE_REFUSED_AS_UNBUILT,)
        return ()
    if observed.template in UNBUILT:
        if observed.http_status != contract.HTTP_NOT_IMPLEMENTED:
            return (FAULT_UNBUILT_ROUTE_DID_NOT_REFUSE,)
        return ()
    return (FAULT_TEMPLATE_OUTSIDE_THE_PARTITION,)


def honesty_faults(observed: Observed) -> tuple[str, ...]:
    """Every way this answer is dishonest about itself. THE CHECK A4 GRADES.

    Deliberately NOT a call through to ``contract.contract_problems``. That
    function grades an envelope against the envelope's own rules and is perfectly
    happy with a conforming 200 on a route whose layer does not exist; the
    partition is a fact about this repository that the envelope cannot know.

    Args:
        observed: The reduced answer.

    Returns:
        Fault ids from this module's own vocabulary. Empty when honest.
    """
    return _body_faults(observed) + _partition_faults(observed)


def describe(observations: tuple[Observed, ...], wanted: frozenset[str]) -> str:
    """A failure line naming the route and the fault, and nothing else.

    Args:
        observations: What came back.
        wanted: The fault ids this arm is about.

    Returns:
        A one-line summary. Route templates and fault ids only.
    """
    parts = [
        f"{item.template} {item.http_status} {fault}"
        for item in observations
        for fault in honesty_faults(item)
        if fault in wanted
    ]
    return "; ".join(parts)


