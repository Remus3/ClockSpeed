#: The suite's own redactor rewrote the body, so it held a home path or an
#: account name. Reported as its own id because the redactor answers "something
#: of mine is in here" without saying which of its two classes it was.
CLASS_REDACTOR_FIRED: Final = "redactor-rewrote-the-body"

#: A world token rendered unmasked. NOT one of the four classes ``tests/
#: conftest.py`` registers - those are about a failure report, and this is about
#: a response body - so it carries its own id rather than borrowing
#: ``CLASS_WORLD_NAME``, which names the operator-authored world name instead.
CLASS_SAVE_IDENTIFIER: Final = "save-identifier"

#: A platform account id as the save directory spells one: a long run of digits.
#: The floor is set well above any count, offset, numerator or denominator this
#: API has a reason to render, because a shape detector that fires on an ordinary
#: integer is a detector that gets deleted.
#:
#: THE THREE ANCHORS ARE NOT DECORATION, AND CS-977 MEASURED WHY. ``/api/map``
#: renders a coordinate as the shortest round-trip decimal of a float32 widened
#: to a double, and such a string carries up to seventeen significant digits - so
#: a bare run of fifteen fired on the FRACTIONAL TAIL of an ordinary node
#: coordinate, on every real save, reporting a platform account id that was not
#: there. The two leading lookbehinds say "start of a maximal digit run, and not
#: the tail of a decimal fraction"; the trailing one says "end of that run". A
#: real account id is preceded by a path separator, a quote or a letter and never
#: by ``<digit>.``, so all three spellings the save directory uses still fire -
#: which ``test_the_personal_data_detector_fires_on_a_planted_value_of_every_class``
#: proves rather than this comment asserting it.
_MIN_ACCOUNT_ID_DIGITS: Final = 15
_ACCOUNT_ID_DIGITS: Final = re.compile(
    rf"(?<![0-9])(?<![0-9]\.)\d{{{_MIN_ACCOUNT_ID_DIGITS},}}(?![0-9])"
)

#: The other spelling of the same identifier, as a 32 character hexadecimal id.
_ACCOUNT_ID_HEX: Final = re.compile(r"(?<![0-9A-Za-z])[0-9a-fA-F]{32}(?![0-9A-Za-z])")

#: A save identifier at its MEASURED length, imported rather than restated. The
#: character class is the one a base64-spelled identifier uses. ``masked_token``
#: renders a prefix plus a short digest and breaks on the colon, so a masked
#: token cannot match this.
_IDENTIFIER_CHARS: Final = "A-Za-z0-9+/=-"
_IDENTIFIER_RUN: Final = rf"[{_IDENTIFIER_CHARS}]{{{WORLD_TOKEN_LENGTH}}}"
_SAVE_IDENTIFIER = re.compile(
    rf"(?<![{_IDENTIFIER_CHARS}]){_IDENTIFIER_RUN}(?![{_IDENTIFIER_CHARS}])"
)


def _known_safe_runs() -> frozenset[str]:
    """Published vocabulary words that happen to be token-shaped.

    A reason code is authored in this repository and is not personal data, but
    ``search_space_too_large`` is exactly as long as a save identifier. Without
    this subtraction the detector would report a correct refusal as a leak, and
    a detector with a false positive is a detector someone switches off.

    Returns:
        Every closed-vocabulary word this API can put on the wire.
    """
    words: set[str] = set()
    words.update(contract.REASONS)
    words.update(contract.STATUSES)
    words.update(contract.PROBLEM_CODES)
    for template in BOOTSTRAP_ENDPOINTS:
        words.update(part for part in re.split(r"[^A-Za-z0-9_]+", template) if part)
    return frozenset(words)


KNOWN_SAFE_RUNS: Final = _known_safe_runs()


@cache
def game_content_runs() -> frozenset[str]:
    """Token-shaped runs this machine's own GAME DATA legitimately contains.

    WHY THIS EXISTS, AND IT IS A MEASUREMENT RATHER THAN A CONVENIENCE. CS-912
    put ``/api/registry`` on the wire, and the shipped document holds three
    ClassNames whose middle segment is EXACTLY as long as a save identifier and
    is drawn from exactly its character class - two wall-mounted power poles and
    a pressure conversion cube. The underscores around each segment are not in
    :data:`_IDENTIFIER_CHARS`, so each one is a bounded run of the right length
    and the detector reported the item catalogue as a leaked save token. That is
    a FALSE POSITIVE, and a leak detector that cries wolf on the game's own
    vocabulary is one somebody eventually deletes.

    WHAT IS AND IS NOT GIVEN UP HERE. The pattern, both lookarounds and the
    length are UNCHANGED - nothing about the shape rule is relaxed, and every
    other body on the wire is scanned exactly as before. What is subtracted is
    the set of runs found in a registry read INDEPENDENTLY of the server under
    test, and a registry is built from the shipped game document alone:
    ``clockspeed/surface/providers.py`` reaches only for the install, so no save
    byte can reach any string below. That is why the subtraction cannot mask a
    save identifier, and it is also why the subtraction is derived at run time
    instead of being written down - a hardcoded ClassName would be game content
    committed to a tracked file (non-negotiable 2) and would go stale on the
    next patch.

    NOT READ FROM THE ARTIFACT UNDER TEST, DELIBERATELY. Harvesting the safe runs
    out of the ``/api/registry`` BODY would be the cheaper implementation and a
    worthless one: a body that had somehow acquired a real token would whitelist
    it and grade itself clean. The independent read is what makes this a second
    opinion rather than an agreement.

    MEASURED ON THIS MACHINE: four members, and the fourth was a surprise worth
    recording - ``unresolved-produced-in`` is a warning CODE authored in
    ``clockspeed/data/registry.py``, not game content, and it is token-shaped
    because a hyphen is in the identifier alphabet. It arrives here rather than
    through :func:`_known_safe_runs` because that function reads the SURFACE
    layer's vocabulary and this code belongs to the data layer's. Either home is
    defensible; what is not defensible is neither, which is what it had before
    any registry reached the wire.

    Returns:
        The runs, or an empty set on a machine with no game installed - where
        every registry answer is a 503 that carries no content at all.
    """
    registry = InstalledRegistryProvider().registry()
    if registry is None:
        return frozenset()
    text: list[str] = []
    for key, item in registry.items.items():
        text.extend((key, item.display_name))
    for key, recipe in registry.recipes.items():
        text.extend((key, recipe.display_name))
        text.extend(side.item_key for side in recipe.inputs + recipe.outputs)
        text.extend(recipe.produced_in)
    for key, building in registry.buildings.items():
        text.extend((key, building.display_name))
    for warning in registry.warnings:
        text.extend((warning.code, warning.subject))
    text.extend(registry.unknown_groups)
    found: set[str] = set()
    for value in text:
        found.update(_SAVE_IDENTIFIER.findall(value))
    return frozenset(found)


#: THE CHARACTER EVERY NON-PLAIN SPELLING BELOW IS DERIVED FROM. Named rather
#: than respelled inline because two arms turn on it, and because WHETHER A PATH
#: CARRIES IT IS A STATIC PROPERTY OF THAT PATH - which is what makes it a
#: legitimate skip predicate. No defect in the encoder under test can flip it.
BACKSLASH: Final = "\\"


def _spellings_of(plain: str) -> tuple[str, ...]:
    """Every way one path string can appear in a JSON body.

    MEASURED, NOT REASONED. The plain string was the whole of this check until a
    throwaway server was made to leak ``str(Path.home())`` through a real
    response. The JSON encoder DOUBLES every separator on a backslash platform,
    so the path reaches the wire in a spelling the plain substring test does not
    match, and that test missed it entirely. The suite redactor happened to
    catch the same body by a different rule, and a check that only works when
    another check works is not a check. The URL-quoted spelling is here for the
    same reason and has not been observed, only anticipated.

    EVERY NON-PLAIN SPELLING IS DERIVED FROM :data:`BACKSLASH`, so on a path
    carrying none of them the set COLLAPSES TO THE PLAIN STRING ALONE. That
    collapse is the whole subject of the skip in
    :func:`test_the_home_path_detector_survives_the_encoder_that_once_defeated_it`,
    and taking the parameter rather than reading ``Path.home()`` directly is
    what lets an arm grade this model on a machine whose own home cannot.

    Args:
        plain: A path, exactly as the filesystem spells it.

    Returns:
        The spellings, longest first. Empty when ``plain`` is empty.
    """
    if not plain:
        return ()
    spellings = {
        plain,
        plain.replace(BACKSLASH, BACKSLASH * 2),
        plain.replace(BACKSLASH, "/"),
        plain.replace(BACKSLASH, "%5C"),
    }
    return tuple(sorted(spellings, key=len, reverse=True))


def _home_spellings() -> tuple[str, ...]:
    """Every way this machine's home directory can appear in a JSON body.

    Returns:
        The spellings, longest first.
    """
    return _spellings_of(str(Path.home()))


HOME_SPELLINGS: Final = _home_spellings()


def _personal_data_classes(text: str) -> tuple[str, ...]:
    """Which personal-data classes this text carries, as ids and never as values.

    THE RETURN IS A CLOSED VOCABULARY ON PURPOSE. This result reaches a failure
    message, and a failure message that quotes what it found publishes the very
    thing the arm exists to keep out of a response body.

    Args:
        text: A response body, exactly as it came off the wire.

    Returns:
        The class ids found, in a stable order. Empty when the text is clean.
    """
    found: list[str] = []

    if redact_personal_data(text) != text:
        found.append(CLASS_REDACTOR_FIRED)

    if any(spelling in text for spelling in HOME_SPELLINGS):
        found.append(CLASS_HOME_PATH)

    account = Path.home().name
    if account and re.search(rf"(?<![0-9A-Za-z_]){re.escape(account)}(?![0-9A-Za-z_])", text):
        found.append(CLASS_ACCOUNT_NAME)

    if _ACCOUNT_ID_DIGITS.search(text) or _ACCOUNT_ID_HEX.search(text):
        found.append(CLASS_ACCOUNT_ID)

    safe = KNOWN_SAFE_RUNS | game_content_runs()
    if any(run not in safe for run in _SAVE_IDENTIFIER.findall(text)):
        found.append(CLASS_SAVE_IDENTIFIER)

    return tuple(found)


