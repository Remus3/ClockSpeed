"""CS-601 slice S7 - the acceptance arms for the local HTTPS dashboard and JSON API.

WHAT THIS GRADES, AND WHY IT IS WRITTEN WITHOUT READING THE IMPLEMENTATION.
``ROADMAP.md`` states the acceptance criterion for CS-601 as "every endpoint
listed in BOOTSTRAP section 7.1 responds, and the self-signed certificate is
generated by a tracked script into a gitignored location". A test derived from
the server module would agree with the server module by construction and would
grade nothing, so the endpoint set here is DERIVED FROM ``BOOTSTRAP.md`` TWICE -
parsed out of section 7.1 at run time, and transcribed by hand into
:data:`BOOTSTRAP_NINE` - and the two are asserted equal before either is used.
The route table is then asserted to MATCH that derivation rather than to define
it. Importing the nine from ``ROUTES`` and asserting ``ROUTES`` holds them is a
tautology, and a tautology is what an acceptance test must not be.

THE FOUR HONESTY ARMS, AND WHY EACH ONE EXISTS.

  A1  A TRANSPORT CODE AND A BODY CANNOT DISAGREE, IN BOTH DIRECTIONS. A 200
      that says anything but "ok", a refusal that says "ok", a 501 with no
      blocking item, a 200 with no ``data`` or with a ``reason``: each is a
      response that two readers describe differently, because a proxy reads the
      code and a dashboard reads the body.

  A2  THE PLACEHOLDER HAS A MACHINE-ENFORCED EXPIRY. Every ``blocked_by`` a
      running endpoint actually returns must still be an OPEN item line in
      ``ROADMAP.md``. When that item closes and its line leaves the file, this
      arm goes RED: the refusal cannot outlive its reason. This is deliberately
      NOT the same subject as the closed vocabulary in
      ``clockspeed/surface/api/contract.py``, which is a constant a sibling
      module grades; this grades the values that came off the wire.

  A3  THE PARTITION IS DECLARED AS DATA, AND IT CUTS BOTH WAYS. Four routes are
      backed by a layer that exists on disk and must never answer 501; five are
      not and must answer exactly 501. When a phase 5 endpoint becomes real this
      goes RED and forces it across the line, so a REAL implementation cannot
      hide behind a placeholder either.

  A4  THE VACUITY CONTROL, WHICH IS THE ONE THAT MATTERS MOST. A1 through A3
      iterate, and every one of them passes over an empty route table. So the
      route count is bound to a SCALAR and asserted BEFORE anything is iterated,
      and a conforming-looking answer is PLANTED on a route the partition says
      is unbuilt, with the check asserted to REJECT it. The most recent commit
      on this branch records a guard that was green because it graded nothing.

  A5  THE CERTIFICATE LOCATION IS PROVED IGNORED BY ASKING GIT, not by reading
      ``.gitignore`` and pattern-matching it. Reading the file would test this
      module's parser; ``git check-ignore`` tests the thing that decides.

  A6  NO RESPONSE BODY CARRIES PERSONAL DATA, and the detector is proved to fire
      on a planted value of every class it claims. Raw bodies NEVER LEAVE
      :func:`_reduce`: what crosses into an asserting frame is a closed
      vocabulary of class ids and route templates, never a value. pytest renders
      the asserted EXPRESSION independently of the message, and this repository
      shipped a real leak inside its own personal-data guard exactly that way.

EVERY ARM VERIFIES THE CERTIFICATE. ``check_hostname`` is left at the True that
``ssl.create_default_context`` sets and the server is addressed by the address
the certificate carries an IP SAN for, so a handshake that succeeds is evidence
about the certificate. A client that validates nothing completes a handshake
against any certificate whatsoever, which is why the positive arms are paired
with :func:`test_a_client_carrying_only_the_system_trust_store_is_rejected`.

NOTHING HERE BINDS A PORT FROM THE RESERVED BAND. Every listener is bound on
port zero and the operating system picks it, so a test run cannot collide with a
real dashboard the operator is running.
"""

