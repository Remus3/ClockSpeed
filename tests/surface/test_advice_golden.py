"""CS-1371 arm 4: with no target stated, the advice body is byte-same as a captured golden.

THE GOLDEN IS OLDER THAN THE ITEM. ``tests/surface/golden/advice_no_target.json`` was
written by :func:`no_target_body` in this module, at the parent commit of CS-1371's
advisor slice, before any change that slice made: the same helper over the same world.
It is not regenerated by anything here, so a later change to the body has to change the
file on purpose and be seen doing it.

THE COMPARISON IS OF RAW BYTES. ``read_text`` hides a CRLF, so the file is read with
``read_bytes`` and compared whole against what
:func:`clockspeed.surface.api.contract.encode` puts on the wire plus one LF.

WHAT THIS CANNOT PROVE BY GOING RED FIRST. It passes before the item and after it, because
byte-same is the claim. Its proof is that a mutated body reddens it, which
:func:`test_a_changed_body_is_told_from_the_golden` keeps, beside the hand-run mutation the
slice reported.

EVERYTHING HERE IS SYNTHETIC. The world is ``tests/advisor/test_world_advice.py``'s
``gap_world``, the registry its ``synthetic_registry``, and the clock a fixed instant. Every
store lives in a temporary directory. No save and no install is read.
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

from clockspeed.surface.api import advice as advice_endpoint
from clockspeed.surface.api import contract, routes
from clockspeed.surface.providers import StoreAdviceSource
from tests.advisor import test_world_advice as world_fixtures
from tests.advisor.build_fixtures import docs_pin
from tests.surface import test_map as map_fixtures

#: The body captured at the parent commit.
GOLDEN: Final = Path(__file__).resolve().parent / "golden" / "advice_no_target.json"

#: The instant the injected clock answers.
NOW: Final = 1000

#: The cards the fixture world fires, so a body of no cards cannot pass as byte-same.
GOLDEN_CARDS: Final = 1

#: Highest byte the wire may carry.
LAST_ASCII: Final = 0x7F


def no_target_body(directory: Path) -> bytes:
    """The bytes ``GET /api/advice`` answers with no parameter, through the real route table.

    Args:
        directory: Where the advice stores live. Empty, so nothing is recorded.

    Returns:
        The encoded body and one LF, which is what the golden file holds.
    """
    built = routes.build_routes(
        map_fixtures._Worlds(world_fixtures.gap_world()),  # noqa: SLF001
        map_fixtures._Registries(world_fixtures.synthetic_registry()),  # noqa: SLF001
        StoreAdviceSource(directory, clock=lambda: NOW),
    )
    handlers = {(route.method, route.template): route.handler for route in built}
    response = handlers[(advice_endpoint.METHOD_GET, advice_endpoint.ENDPOINT)]({})
    status = response.http_status
    assert status == contract.HTTP_OK
    return contract.encode(response.payload) + b"\n"


def test_the_no_target_body_is_byte_same_as_the_golden(tmp_path: Path) -> None:
    served = no_target_body(tmp_path)
    captured = GOLDEN.read_bytes()
    same = served == captured
    assert same, "the no-target advice body moved from the golden captured before CS-1371"


def test_the_golden_is_one_body_and_one_lf_holding_a_card() -> None:
    captured = GOLDEN.read_bytes()
    one_line = captured.count(b"\n") == 1 and captured.endswith(b"\n") and b"\r" not in captured
    assert one_line
    cards = captured.count(b'"rule_id":')
    assert cards == GOLDEN_CARDS


def _forbidden_fragments() -> tuple[tuple[str, bytes], ...]:
    """What the golden may never hold, by name, so an assertion renders no token."""
    return (
        ("backslash", b"\\"),
        ("world token", world_fixtures.gap_world().token.encode("ascii")),
        ("docs hash", docs_pin().encode("ascii")),
        ("game path", b"/Game/"),
        ("user path", b"/Users/"),
        ("save file", b".sav"),
    )


def test_the_golden_holds_no_backslash_token_path_hash_or_high_byte() -> None:
    captured = GOLDEN.read_bytes()
    highest = max(captured)
    assert highest <= LAST_ASCII
    named = [name for name, fragment in _forbidden_fragments() if fragment in captured]
    assert named == []


def test_a_changed_body_is_told_from_the_golden(tmp_path: Path) -> None:
    """The control: one byte moved is not byte-same, so the arm above can go red."""
    served = no_target_body(tmp_path)
    moved = served.replace(b'"new_world":true', b'"new_world":false')
    assert moved != served
    same = moved == GOLDEN.read_bytes()
    assert not same
