# SEAM DISCIPLINE (BOOTSTRAP.md section 6).
# Each layer consumes only the layer below it through a stated model.
# solve/ never reads a save. advisor/ never reads the raw docs file.
# surface/ never computes. A layer that reaches past its neighbor is a
# design bug.
#
# This layer is the TOP of the stack. Below it are the models produced by
# clockspeed.advisor, clockspeed.audit, clockspeed.progress and
# clockspeed.solve. surface/ never computes: no arithmetic, no ranking, no
# recipe choice, no threshold decision. If a number has to be derived to
# render a page, it is derived below and handed up. A computation here is
# invisible to the solver's tests and drifts from the advice it is meant to
# display.
#
# Two operational constraints this layer carries alone:
#   - The port is ALLOCATED, recorded once in the project configuration, and
#     read from there. It is not restated in code (CONVENTIONS.md section 2).
#   - The certificate is self-signed and generated by a tracked script into a
#     gitignored location. The script is the artifact; the key never is. The
#     companion window handles that certificate cleanly rather than disabling
#     certificate validation wholesale (BOOTSTRAP.md section 7.2).
